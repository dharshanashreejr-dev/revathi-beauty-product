export const pname = (name: string, lang: Lang): string => {
  if (lang === 'en') return name
  let s = name
  for (const k of Object.keys(BRAND)) s = s.replace(k, BRAND[k][lang])
  return s.split(' ').map(w => (WORDS[w] ? WORDS[w][lang] : w)).join(' ')
}
